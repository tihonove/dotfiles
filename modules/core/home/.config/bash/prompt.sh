# Поздняя часть конфига интерактивного bash: промпт.
#
# Подключается вторым, ОТДЕЛЬНЫМ блоком в самом конце ~/.bashrc — в отличие от
# rc.sh, который идёт в начало. Причина ровно одна, и она из практики: базовый
# образ devcontainer задаёт свой PS1 функцией __bash_prompt в конце своего
# ~/.bashrc. Пока промпт настраивался в rc.sh, starship отрабатывал первым и
# через полторы сотни строк его молча затирали. Внешне это выглядело так, будто
# starship не установлен.
#
# Отсюда правило: всё, что борется за PS1 и PROMPT_COMMAND, живёт здесь.
# Всё остальное (PATH, история, автодополнение, загрузка ble.sh) — в rc.sh,
# потому что там наоборот важно отработать раньше чужих строк.

# Неинтерактивный шелл — ничего не делаем. Дубль гарда из rc.sh: файл
# подключается своим блоком и на rc.sh не опирается.
case $- in
    *i*) ;;
      *) return;;
esac

# Промпт. Конфиг — ~/.config/starship.toml (дефолтный путь starship).
# Гард через `command -v` обязателен: если бинарника нет или он битый,
# подстановка `$(...)` подвесит старт шелла навсегда, а не упадёт с ошибкой.
command -v starship >/dev/null && eval "$(starship init bash)"

# Подцепить ble.sh — обязательно последней строкой, после starship: с
# --attach=none ble.sh не трогает PROMPT_COMMAND, и starship успевает поставить
# свой промпт первым.
#
# Условие само себе гард: если ble.sh не загрузился в rc.sh, BLE_VERSION пуст.
[[ ! ${BLE_VERSION-} ]] || ble-attach
