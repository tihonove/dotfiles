#!/bin/sh
# Обёртка для `geninclude theme.sh` из kitty.conf.
#
# geninclude запускает программу БЕЗ аргументов и берёт её stdout как конфиг, а
# сам генератор палитры общий на всю сессию и выбирает потребителя аргументом —
# отсюда эта строчка. Запускается при каждой загрузке конфига, в том числе по
# SIGUSR1, поэтому цвета всегда соответствуют текущей теме.
#
# Путь абсолютный: kitty стартует не из login-шелла (см. greetd в ~/.system-setup),
# и ~/.local/bin в PATH может не оказаться.
exec "$HOME/.local/bin/theme-colors" kitty
